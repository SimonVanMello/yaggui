// Writes Casks/yaggui.rb, the Homebrew cask of the SimonVanMello/homebrew-yaggui tap, which
// installs the .dmg files of a GitHub release.
// Usage: node scripts/homebrew.mjs <x.y.z> <sha256 of the aarch64 .dmg> <sha256 of the x64 .dmg> <out dir>
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const tauri = JSON.parse(readFileSync(`${root}src-tauri/tauri.conf.json`, 'utf8'));

const [version, sha256Arm, sha256Intel, outDir] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) fail(`invalid version: ${version}`);
for (const sha256 of [sha256Arm, sha256Intel]) {
  if (!/^[0-9a-f]{64}$/.test(sha256 ?? '')) fail(`invalid sha256: ${sha256}`);
}
if (!outDir) fail('missing output directory');

const { productName, identifier } = tauri;
const homepage = tauri.bundle.homepage;
const desc = tauri.bundle.shortDescription;
// Tauri's default when bundle.macOS.minimumSystemVersion is unset (10.13) is older than any macOS
// Homebrew supports, so the cask only declares a version when the config sets one.
const minimumSystemVersion = tauri.bundle.macOS?.minimumSystemVersion;

for (const value of [productName, identifier, homepage, desc, minimumSystemVersion]) {
  if (value !== undefined && (typeof value !== 'string' || /["#\\\n]/.test(value))) {
    fail(`unsafe value: ${value}`);
  }
}

// Tauri names the .dmg `<productName>_<version>_<arch>.dmg`, with `aarch64` or `x64`.
const url = (arch) =>
  `${homepage}/releases/download/v#{version}/${productName}_#{version}_${arch}.dmg`;

// Homebrew names macOS releases by symbol; only the ones it still supports are listed.
const macosNames = {
  11: 'big_sur',
  12: 'monterey',
  13: 'ventura',
  14: 'sonoma',
  15: 'sequoia',
  26: 'tahoe',
};
// The app replaces itself with the Tauri updater: `auto_updates` tells `brew upgrade` to leave
// it alone (unless `--greedy`), so Homebrew does not fight the updater over the version.
const autoUpdates = '\n  auto_updates true';
// `brew style` requires every macOS-only cask to declare `depends_on :macos`.
let dependsOn = '\n  depends_on :macos\n';
if (minimumSystemVersion) {
  const name = macosNames[minimumSystemVersion.split('.')[0]];
  if (!name) fail(`no Homebrew name for macOS ${minimumSystemVersion}`);
  dependsOn = `\n  depends_on macos: ">= :${name}"\n`;
}

const cask = `# Generated by scripts/homebrew.mjs in ${homepage}: edit the generator, not this file.
cask "${productName}" do
  version "${version}"

  on_arm do
    sha256 "${sha256Arm}"

    url "${url('aarch64')}"
  end
  on_intel do
    sha256 "${sha256Intel}"

    url "${url('x64')}"
  end

  name "${productName}"
  desc "${desc}"
  homepage "${homepage}"

  livecheck do
    url :url
    strategy :github_latest
  end
${autoUpdates}${dependsOn}
  app "${productName}.app"

  zap trash: [
    "~/Library/Application Support/${identifier}",
    "~/Library/Caches/${identifier}",
    "~/Library/HTTPStorages/${identifier}",
    "~/Library/Logs/${identifier}",
    "~/Library/Preferences/${identifier}.plist",
    "~/Library/Saved Application State/${identifier}.savedState",
    "~/Library/WebKit/${identifier}",
  ]

  # BEGIN quarantine caveat: remove once the macOS build is notarized.
  caveats <<~EOS
    ${productName} is not notarized yet, so Gatekeeper blocks it on first launch.
    To allow it, clear the quarantine attribute:
      xattr -dr com.apple.quarantine /Applications/${productName}.app
  EOS
  # END quarantine caveat
end
`;

mkdirSync(join(outDir, 'Casks'), { recursive: true });
writeFileSync(join(outDir, 'Casks', `${productName}.rb`), cask);
console.log(cask);

function fail(message) {
  console.error(message);
  process.exit(1);
}
