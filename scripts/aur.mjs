// Writes the PKGBUILD and .SRCINFO of the `yaggui-bin` AUR package, which repackages the .deb
// of a GitHub release. Usage: node scripts/aur.mjs <x.y.z> <sha256 of the .deb> <out dir> [pkgrel]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const tauri = JSON.parse(readFileSync(`${root}src-tauri/tauri.conf.json`, 'utf8'));

const [version, sha256, outDir, pkgrel = '1'] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) fail(`invalid version: ${version}`);
if (!/^[0-9a-f]{64}$/.test(sha256 ?? '')) fail(`invalid sha256: ${sha256}`);
if (!outDir) fail('missing output directory');
if (!/^[1-9]\d*$/.test(pkgrel)) fail(`invalid pkgrel: ${pkgrel}`);

const url = tauri.bundle.homepage;
const pkg = {
  pkgname: 'yaggui-bin',
  pkgdesc: tauri.bundle.shortDescription,
  pkgver: version,
  pkgrel,
  url,
  arch: ['x86_64'],
  license: [tauri.bundle.license],
  // Runtime libraries of the Tauri webview, and the git binary that yaggui drives.
  depends: ['git', 'gtk3', 'hicolor-icon-theme', 'webkit2gtk-4.1'],
  provides: ['yaggui'],
  conflicts: ['yaggui'],
  // The binary comes without debug info: a -debug package would only hold a dangling link.
  options: ['!debug'],
  source: [
    `yaggui-${version}.deb::${url}/releases/download/v${version}/yaggui_${version}_amd64.deb`,
  ],
  sha256sums: [sha256],
};

for (const value of [pkg.pkgdesc, url, ...pkg.license]) {
  if (typeof value !== 'string' || /['"$`\\\n]/.test(value)) fail(`unsafe value: ${value}`);
}

const quote = (value) => `'${value}'`;
const array = (values) => `(${values.map(quote).join(' ')})`;

const pkgbuild = `# Maintainer: SimonVanMello <https://github.com/SimonVanMello>
# Generated by scripts/aur.mjs in ${url}: edit the generator, not this file.
pkgname=${pkg.pkgname}
pkgver=${pkg.pkgver}
pkgrel=${pkg.pkgrel}
pkgdesc=${quote(pkg.pkgdesc)}
arch=${array(pkg.arch)}
url=${quote(pkg.url)}
license=${array(pkg.license)}
depends=${array(pkg.depends)}
provides=${array(pkg.provides)}
conflicts=${array(pkg.conflicts)}
options=${array(pkg.options)}
source=("yaggui-\${pkgver}.deb::${url}/releases/download/v\${pkgver}/yaggui_\${pkgver}_amd64.deb")
sha256sums=${array(pkg.sha256sums)}

package() {
  bsdtar -xf data.tar.* -C "$pkgdir"
}
`;

// Same field order as `makepkg --printsrcinfo`, which the AUR workflow compares against.
const fields = [
  'pkgdesc',
  'pkgver',
  'pkgrel',
  'url',
  'arch',
  'license',
  'depends',
  'provides',
  'conflicts',
  'options',
  'source',
  'sha256sums',
];
const srcinfo = [
  `pkgbase = ${pkg.pkgname}`,
  ...fields.flatMap((field) => [pkg[field]].flat().map((value) => `\t${field} = ${value}`)),
  '',
  `pkgname = ${pkg.pkgname}`,
  '',
].join('\n');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'PKGBUILD'), pkgbuild);
writeFileSync(join(outDir, '.SRCINFO'), srcinfo);
console.log(pkgbuild);

function fail(message) {
  console.error(message);
  process.exit(1);
}
