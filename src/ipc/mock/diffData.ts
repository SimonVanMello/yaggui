import type { FileMode, FileStatus, LfsObject, TextEncoding } from '../bindings';

/** A changed path of the mock repositories, with the content of both sides. */
export interface MockFileChange {
  path: string;
  oldPath?: string;
  status: FileStatus;
  oldMode: FileMode | null;
  newMode: FileMode | null;
  /** `null` = side absent. */
  old: string | null;
  new: string | null;
  similarity?: number;
  binary?: { oldSize: number | null; newSize: number | null };
  /** Above the size guards: the content is not generated, only described. */
  tooLarge?: { oldSize: number | null; newSize: number | null };
  submodule?: { oldCommit: string | null; newCommit: string | null };
  /** Stored with Git LFS: the pointers, never a text diff. */
  lfs?: { old: LfsObject | null; new: LfsObject | null };
  /** Encodings the real backend would detect from the bytes. */
  oldEncoding?: TextEncoding;
  newEncoding?: TextEncoding;
}

