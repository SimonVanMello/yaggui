/** A long, realistic TypeScript module: P-06 is measured on it. */
function layoutModule(variant: 'old' | 'new'): string {
  const out = [
    "import type { GraphPage, LaneColor } from '../../ipc';",
    '',
    '/** Lane assignment of the commit graph, computed page by page. */',
  ];
  for (let i = 0; i < 380; i++) {
    const tweak = variant === 'new' && i % 47 === 3;
    out.push(
      '',
      `/** Step ${String(i)} of the incremental layout. */`,
      `export function placeRow${String(i)}(page: GraphPage, lanes: number[]): number {`,
      `  const parents = page.parents[${String(i)}] ?? [];`,
      tweak
        ? `  let lane = lanes.indexOf(page.ids[${String(i)}] ?? -1, 0);`
        : `  let lane = lanes.indexOf(page.ids[${String(i)}] ?? -1);`,
      '  if (lane < 0) {',
      '    lane = lanes.length;',
      `    lanes.push(page.ids[${String(i)}] ?? -1);`,
      '  }',
      tweak
        ? `  return reserve(lanes, lane, parents.length + 1);`
        : `  return reserve(lanes, lane, parents.length);`,
      '}',
    );
  }
  out.push(
    '',
    'function reserve(lanes: number[], lane: number, count: number): number {',
    '  return Math.min(lanes.length, lane + count);',
    '}',
    '',
  );
  return out.join('\n');
}

function canvas(variant: 'old' | 'new'): string {
  const lines = [
    "import { useEffect, useRef } from 'react';",
    '',
    "import { drawLanes } from './drawLanes';",
    '',
    'interface Props {',
    '  rows: GraphRow[];',
    variant === 'old' ? '  rowHeight: number;' : '  rowHeight: number; // CSS pixels',
    '}',
    '',
    'export function GraphCanvas({ rows, rowHeight }: Props) {',
    '  const ref = useRef<HTMLCanvasElement>(null);',
    '  useEffect(() => {',
    variant === 'old'
      ? '    drawLanes(ref.current, rows, rowHeight);'
      : '    drawLanes(ref.current, rows, rowHeight, window.devicePixelRatio);',
    '  }, [rows, rowHeight]);',
    '  return <canvas ref={ref} />;',
    '}',
  ];
  return `${lines.join('\n')}\n`;
}

function generatedLanes(): string {
  const lines = ['// Generated by scripts/lanes.mjs. Do not edit.', 'export const LANES = ['];
  for (let i = 0; i < 4_800; i++) {
    lines.push(
      `  { id: ${String(i)}, color: 'lane-${String(i % 8)}', parents: [${String(Math.max(0, i - 1))}] },`,
    );
  }
  lines.push('];', '');
  return lines.join('\n');
}

/** `oid` of a mock LFS object: `sha256:` and 64 hex digits derived from `seed`. */
export function mockLfsOid(seed: string): string {
  // FNV-1a over the whole seed, then expanded: close seeds give unrelated ids.
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619);
  let hex = '';
  while (hex.length < 64) {
    h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0;
    hex += h.toString(16).padStart(8, '0');
  }
  return `sha256:${hex.slice(0, 64)}`;
}

