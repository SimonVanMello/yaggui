/** Generic working tree for the other mock repositories, sized by their dirty counts. */
export function genericWip(counts: {
  staged: number;
  unstaged: number;
  untracked: number;
  conflicted: number;
}): { staged: MockFileChange[]; unstaged: MockFileChange[] } {
  const modified = (path: string): MockFileChange => ({
    path,
    status: 'modified',
    oldMode: 'regular',
    newMode: 'regular',
    old: 'value = 1\n',
    new: 'value = 2\n',
  });
  const range = (n: number) => Array.from({ length: n }, (_, i) => i + 1);
  return {
    staged: range(counts.staged).map((i) => modified(`staged/file${String(i)}.c`)),
    unstaged: [
      ...range(counts.conflicted).map((i): MockFileChange => ({
        path: `conflict/file${String(i)}.c`,
        status: 'conflicted',
        oldMode: null,
        newMode: null,
        old: null,
        new: null,
      })),
      ...range(counts.unstaged).map((i) => modified(`changed/file${String(i)}.c`)),
      ...range(counts.untracked).map((i): MockFileChange => ({
        path: `new/file${String(i)}.c`,
        status: 'untracked',
        oldMode: null,
        newMode: 'regular',
        old: null,
        new: 'new\n',
      })),
    ],
  };
}
