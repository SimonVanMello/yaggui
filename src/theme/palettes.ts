// Color themes of the catalogue (F-320), besides the hand-tuned Graphite, Paper and Terminal
// (graphite.css, paper.css, terminal.css). `pnpm themes` turns them into themes.generated.css.
//
// Values come from each theme's published palette. Text, accent, status and lane colors are
// then moved as little as needed to pass the contrast checks of src/theme/contrast.node.test.ts:
// keep the published value here, the generator does the adjusting.
//
// Fields: surfaces (bg app, panel side panels, elevated dialogs, hover, selected, titlebar,
// input), text fg / fg2 / fg3, borders border / borderStrong, accent and status colors, 8 graph
// lanes, syntax [keyword, string, tag, function], 16 ANSI colors (normal then bright).

export type ThemeFamily = 'yaggui' | 'catppuccin' | 'vscode' | 'jetbrains' | 'github' | 'classics';

export interface ThemePalette {
  id: string;
  name: string;
  family: Exclude<ThemeFamily, 'yaggui'>;
  dark: boolean;
  bg: string;
  panel: string;
  elevated: string;
  hover: string;
  selected: string;
  titlebar: string;
  input: string;
  fg: string;
  fg2: string;
  fg3: string;
  border: string;
  borderStrong: string;
  accent: string;
  success: string;
  warning: string;
  danger: string;
  info: string;
  /** The 8 graph lanes. */
  lanes: readonly string[];
  /** Keyword, string, tag, function. */
  syntax: readonly [string, string, string, string];
  /** The 16 ANSI colors of the integrated terminal, normal then bright. */
  ansi: readonly string[];
}

